-- Pre-render: pulls posts from Lawrence's Substack RSS feed into shelf/substack.yml
-- (generated, not committed), which the Analysis lists and the site feed read alongside
-- shelf/analysis.yml. A post that already has an entry in analysis.yml (same link) is
-- skipped, as is one with a summary page in analysis/, so a hand-written entry always wins.
-- If the feed can't be fetched, the last good file is kept and the build carries on.

local FEED = os.getenv('SUBSTACK_FEED') or 'https://ajaypong.substack.com/feed'
local OUT = 'shelf/substack.yml'

local function read(path)
  local f = io.open(path, 'r')
  if not f then return nil end
  local s = f:read('a')
  f:close()
  return s
end

local function write(path, s)
  local f = assert(io.open(path, 'w'))
  f:write(s)
  f:close()
end

-- Compare links without query strings or trailing slashes.
local function key(url)
  return (url:gsub('[?#].*$', ''):gsub('/+$', ''))
end

local function text(s)
  s = s:match('^%s*<!%[CDATA%[(.-)%]%]>%s*$') or s
  s = s:gsub('&#x(%x+);', function(h) return utf8.char(tonumber(h, 16)) end)
       :gsub('&#(%d+);', function(d) return utf8.char(tonumber(d)) end)
       :gsub('&quot;', '"'):gsub('&apos;', "'"):gsub('&lt;', '<'):gsub('&gt;', '>'):gsub('&amp;', '&')
  return (s:gsub('%s+', ' '):gsub('^ ', ''):gsub(' $', ''))
end

local MONTHS = { Jan = 1, Feb = 2, Mar = 3, Apr = 4, May = 5, Jun = 6, Jul = 7, Aug = 8, Sep = 9, Oct = 10, Nov = 11, Dec = 12 }

local function iso_date(rfc822)
  local d, mon, y = rfc822:match('(%d+)%s+(%a+)%s+(%d%d%d%d)')
  if not (d and MONTHS[mon]) then return nil end
  return string.format('%s-%02d-%02d', y, MONTHS[mon], tonumber(d))
end

local function quote(s)
  return '"' .. s:gsub('\\', '\\\\'):gsub('"', '\\"') .. '"'
end

local ok, mime, body = pcall(pandoc.mediabag.fetch, FEED)
if not ok or type(body) ~= 'string' or not body:find('<rss') then
  print('substack.lua: could not fetch ' .. FEED .. '; ' .. (read(OUT) and 'keeping the last copy' or 'no Substack posts this build'))
  if not read(OUT) then write(OUT, '[]\n') end
  return
end

local taken = {}
for url in (read('shelf/analysis.yml') or ''):gmatch('path:%s*(%S+)') do taken[key(url)] = true end
-- ...and so does a post with a summary page in analysis/ (its `source:` is the post's link)
local ok_dir, files = pcall(pandoc.system.list_directory, 'analysis')
for _, name in ipairs(ok_dir and files or {}) do
  if name:match('%.qmd$') and not name:match('^_') then
    local src = (read('analysis/' .. name) or ''):match('\nsource:%s*["\']?([^"\'%s]+)')
    if src then taken[key(src)] = true end
  end
end

local out, n = {}, 0
for item in body:gmatch('<item>(.-)</item>') do
  item = item:gsub('<content:encoded>.-</content:encoded>', '')
  local title = item:match('<title>(.-)</title>')
  local link = item:match('<link>(.-)</link>')
  local date = iso_date(item:match('<pubDate>(.-)</pubDate>') or '')
  local desc = item:match('<description>(.-)</description>')
  if title and link and date and not taken[key(text(link))] then
    table.insert(out, '- title: ' .. quote(text(title)))
    desc = desc and text(desc) or ''
    if desc ~= '' then table.insert(out, '  description: ' .. quote(desc)) end
    table.insert(out, '  date: ' .. date)
    table.insert(out, '  path: ' .. quote(text(link)))
    table.insert(out, '  where: Substack')
    n = n + 1
  end
end

write(OUT, '# Generated by scripts/substack.lua from ' .. FEED .. ' at build time. Do not edit:\n'
  .. '# to add tags or an NB number to a post, give it an entry in analysis.yml instead.\n'
  .. (n > 0 and table.concat(out, '\n') .. '\n' or '[]\n'))
print('substack.lua: ' .. n .. ' post(s) from Substack not already in analysis.yml')
